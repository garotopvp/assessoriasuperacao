export function getArtigoById(id: string): Artigo | undefined {
  return artigos.find((a) => a.id === id);
}

export function getArtigosRelacionados(currentId: string, limit: number = 3): Artigo[] {
  return artigos.filter((a) => a.id !== currentId).slice(0, limit);
}

export function getNextArtigo(currentId: string): Artigo | undefined {
  const currentIndex = artigos.findIndex((a) => a.id === currentId);
  if (currentIndex === -1 || currentIndex === artigos.length - 1) return undefined;
  return artigos[currentIndex + 1];
}

export function getPreviousArtigo(currentId: string): Artigo | undefined {
  const currentIndex = artigos.findIndex((a) => a.id === currentId);
  if (currentIndex <= 0) return undefined;
  return artigos[currentIndex - 1];
}
